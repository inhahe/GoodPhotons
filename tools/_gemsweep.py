"""Which piece in gallery_rain actually throws a COLOURED caustic, and from how high?

The user's question was "the sphere's caustic has no colour -- will the glass gyroid give
me colour?".  This is the rig that answers it with numbers instead of theory: one stripped
top-down scene, one piece at a time, floated over a plain white cap in the gallery's own
sun, seen flat from above.

WHY THE OBVIOUS METRIC DOES NOT WORK.  Mode D renders one HERO WAVELENGTH per sample, so a
dispersive caustic arrives as chromatic SPECKLE: every pixel is some random monochromatic
spike and per-pixel saturation measures the sampler, not the optics.  The fix is the same
one the denoiser is built on -- the speckle is zero-mean in CHROMA over a neighbourhood, so
box-averaging in LINEAR light recovers the true local colour.  This downsamples 4x first
and only then asks how saturated the result is.

    CAUSTIC       cells at least CUT x the bare-cap level (default 2x)
    coverage      what fraction of the cap those cells are -- a thin filigree of threads
                  and a broad pool can have identical peak brightness and read nothing
                  alike, and this is the number that separates them
    sat           excess-weighted mean of (max-min)/max over the caustic cells; 0 = white
    peak          brightest single pixel, in multiples of the bare-cap level

AND IT MEASURES THE FLOAT SIDECAR, NOT THE PNG.  Every render here passes ftrace's `-hdr`
and the metering reads the `.pfm`.  This is not a refinement: an 8-bit sRGB PNG clamps at
white, a caustic is by definition the brightest thing in frame, and at the clip point all
three channels are EQUAL -- so the tone map destroys the hue and the peak ratio that this
rig exists to measure.  Every number this file printed before 2026-08-04 came through that
clamp and understates the brightest pieces worst: the winning axicon re-measures at
peak 14.68x / sat 0.355 / spread 0.237 where the PNG had said 5.91x / 0.320 / 0.212.

Usage:
    python scraps/_gemsweep.py piece <name> [drop ...]     orb | gyroid<k> | klein
    python scraps/_gemsweep.py k <drop> [k ...]            gyroid lattice frequency
"""
