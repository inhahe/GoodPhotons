# The SAME axicon, but cut so it READS as a gem: pavilion cone, straight GIRDLE band, and
# (optionally) a crown rising to a table.  The user asked for the scene's upside-down cone to
# be "shaped more like a diamond", and the honest answer to "which is better for caustics" is
# already on file -- a round brilliant loses 5x on coverage and 4x on peak because its 40.75
# deg pavilion TIRs the fire back up at the viewer.  But that verdict is about the PAVILION
# angle, and a gem's silhouette is mostly the girdle line.  So this shape keeps the winning
# 45 deg conical exit face EXACTLY as it is and only adds cuts ABOVE the girdle plane:
#
#   girdle  a straight cylinder of height g on top of the cone.  Predicted free: a ray that
#           enters the flat table crosses no interface until the cone, so it arrives there on
#           the same line it always did, just starting g higher.  Only the rim is touched,
#           because the sun comes in at 45 deg and a band that tall shades / admits a strip of
#           it.  "Predicted free" is why it is MEASURED and not simply asserted.
#   crown   the expensive part, and the one worth a number: a crown facet at angle c refracts
#           a vertical ray inward by c - asin(sin c / n) (15.6 deg for c=34.5 in SF10), so the
#           whole annulus outside the table hits the cone at a different incidence and either
#           lands somewhere else or TIRs.  With table fraction f that annulus is 1 - f^2 of
#           the aperture -- 44% at f=0.75, 72% at a true brilliant's f=0.53.  Sweeping c and f
#           is the only way to find out how much gem silhouette the caustic will pay for.
#
# `gcone[g][/crown/tablefrac]`, e.g. `gcone0.08` (girdle only) or `gcone0.08/34.5/0.75`.
GCONE = """\
isosurface "piece" {{
    material glass
    function {{
        translate {cx} {cy} {cz}
        expr "{e}"
    }}
    contained_by {{ min {x0} {y0} {z0}   max {x1} {y1} {z1} }}
    max_gradient 3
}}
"""


def gcone_body(g, crown, tf, d, R=0.56, h=0.28, ngird=0):
    """Field for the girdled axicon.  R is the girdle radius, h the cone's half-height.

    The solid is {r <= Rad(y)} between two end slabs, and Rad is the MIN of the three
    surfaces of revolution -- pavilion, girdle, crown -- which is exactly how the shape is
    described in words.  The pavilion term (h + y) is the scene's current field verbatim, so
    a `gcone` with g=0 and no crown is bit-identical to `vcone1.0` and can be used as the
    sweep's own control.

    Gradients: the pavilion contributes sqrt(2), the girdle 1, the crown sqrt(1 + cot^2 c)
    (1.77 at c=34.5, 2.92 at c=20), so max_gradient 3 covers the whole family.
    """
    yg = h + g                                     # top of the straight girdle band
    if crown > 0 and tf < 1.0:
        rt = tf * R
        cot = 1.0 / math.tan(math.radians(crown))
        yt = yg + (R - rt) / cot
        rad = f'min(min({h} + y, {R}), {R} - {cot:.6f}*(y - {yg:.6f}))'
    else:
        yt = yg
        # NOTE the parens on the bare-cone form: this is substituted as `sqrt(..) - {rad}`, so
        # an unparenthesised `0.28 + y` silently parses as `(sqrt(..) - 0.28) + y` and renders
        # a completely different solid.  (The `min(...)` form is safe only because the comma
        # already brackets it.)
        rad = f'min({h} + y, {R})' if ngird <= 0 else f'({h} + y)'
    e = f'max(sqrt(x*x + z*z) - {rad}, max(-y - {h}, y - {yt:.6f}))'
    if ngird > 0:
        # A FACETED girdle: n flat vertical chords instead of a cylinder.  This is the one
        # gem cut that is optically free by construction -- a vertical facet's normal is
        # horizontal, so it cannot deviate the descending aperture at all; only the rim rays
        # that would have grazed the cylinder see it.  What it buys is the read: sixteen
        # separate specular glints along the waist is the single most diamond-like cue the
        # piece can carry, and the scene's camera sits 11 deg above the horizon, looking
        # straight at that band.
        #
        # The planes are set at d = R cos(pi/n) so the polygon's CORNERS sit at exactly R and
        # meet the cone's rim flush -- pushing them out to R instead would leave the corners
        # overhanging the pavilion by 1 cm.  And they are applied only ABOVE the girdle plane,
        # as `min(P, y - h)`: below it that term goes negative and imposes nothing, so the
        # conical exit face -- the thing that actually makes the caustic -- is untouched.
        dd = R * math.cos(math.pi / ngird)
        P = None
        for i in range(ngird):
            a = 2 * math.pi * i / ngird
            t = _half((math.cos(a), 0.0, math.sin(a)), f'{dd:.6f}')
            P = t if P is None else f'max({P}, {t})'
        e = f'max({e}, min({P}, y - {h}))'
    return GCONE.format(e=e, **d)


