def gem_body(R, crown, pav, table_h, d, nmain=8, ngirdle=16):
    """A round BRILLIANT cut as an intersection of half-spaces.

    This is the shape the cone sweep points at, built the way the real object is built: a
    flat TABLE on top and a faceted conical PAVILION below.  That combination is a faceted
    axicon -- light enters the table undeviated, and every pavilion facet is a prism at the
    same tilt, so the exit deviation is constant (a line focus, hence bright) while the
    dispersion is a prism's (hence coloured).  It is not a coincidence that this is the cut
    the trade evolved for "fire".

    Standard round-brilliant proportions, all measured from the girdle plane at y=0 with
    girdle radius R: crown angle 34.5 deg, pavilion angle 40.75 deg, table 53% of the girdle
    diameter.  A facet whose plane makes angle t with the horizontal has outward normal at t
    from +y, i.e. n = (sin t cos a, cos t, sin t sin a), and passing it through the girdle
    circle fixes d = R sin t.  The crown apex would then sit at R tan(34.5) = 0.687 R and the
    pavilion culet at -R tan(40.75) = -0.863 R (the textbook 43.1% of diameter); the table
    plane cuts the crown at table_h, leaving a table radius of R(1 - table_h/(R tan crown)).
    Every normal is unit, so the field is Lipschitz-1 and max_gradient 2 is generous.
    """
    ct, pt = math.radians(crown), math.radians(pav)
    planes = [((0.0, 1.0, 0.0), table_h)]
    for i in range(ngirdle):                       # girdle: a polygonal waist
        a = 2 * math.pi * i / ngirdle
        planes.append(((math.cos(a), 0.0, math.sin(a)), R))
    for i in range(nmain):                         # crown bezels
        a = 2 * math.pi * i / nmain
        planes.append(((math.sin(ct) * math.cos(a), math.cos(ct), math.sin(ct) * math.sin(a)),
                       R * math.sin(ct)))
    for i in range(nmain):                         # pavilion mains, offset half a facet
        a = 2 * math.pi * (i + 0.5) / nmain
        planes.append(((math.sin(pt) * math.cos(a), -math.cos(pt), math.sin(pt) * math.sin(a)),
                       R * math.sin(pt)))
    e = _half(planes[0][0], planes[0][1])
    for n, dd in planes[1:]:
        e = f'max({e}, {_half(n, dd)})'
    return GEM.format(e=e, **d)


def facet_body(n, R, h, pav, d):
    """A FACETED axicon: flat table on top, n flat pavilion facets below, all at `pav`.

    The smooth cone wins the caustic sweep but from the scene's low camera (11 deg above the
    horizon) a 45 deg cone is 2x as wide as it is tall and foreshortens into a squat glass
    wedge -- optically right, visually mute.  Every facet of this is at the SAME tilt as the
    cone it replaces, so each is still a prism at the axicon's angle and the optics should
    survive; what changes is that the ring focus is sampled at n discrete azimuths instead of
    continuously, which could either concentrate the cusps or scatter them.  Not derivable --
    measured.

    A pavilion facet at angle t from horizontal has outward normal (sin t cos a, -cos t,
    sin t sin a), and passing it through the girdle circle (radius R at height h) fixes
    d = R sin t - h cos t.
    """
    pt = math.radians(pav)
    planes = [((0.0, 1.0, 0.0), h)]
    for i in range(n):
        a = 2 * math.pi * i / n
        planes.append(((math.sin(pt) * math.cos(a), -math.cos(pt), math.sin(pt) * math.sin(a)),
                       R * math.sin(pt) - h * math.cos(pt)))
    e = _half(planes[0][0], planes[0][1])
    for nn, dd in planes[1:]:
        e = f'max({e}, {_half(nn, dd)})'
    return GEM.format(e=e, **d)


def prism_body(roll, yaw, r, L, d):
    # base at y=-r, two sloped faces meeting at an apex on the z=0 axis, axis along x
    faces = [((0.0, -1.0, 0.0), r), ((0.0, 0.5, 0.86603), r), ((0.0, 0.5, -0.86603), r),
             ((1.0, 0.0, 0.0), L)]
    ns = {f'n{i}': _half(_rot(n, roll, yaw), dd) for i, (n, dd) in enumerate(faces)}
    # the slab needs BOTH sides; fold the -x half-space into the tightest of the three
    ns['n3'] = f'max({ns["n3"]}, {_half(_rot((-1.0, 0.0, 0.0), roll, yaw), L)})'
    return PRISM.format(**ns, **d)

